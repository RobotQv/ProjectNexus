def dataset():
    documents, questions = [], []
    for case in CASES:
        ids = {}
        for kind, title in KINDS.items():
            did = len(documents) + 1
            ids[kind] = did
            documents.append(
                {
                    "id": did,
                    "topic": case["topic"],
                    "kind": kind,
                    "filename": f"{case['topic']}-{title}.md",
                    "text": case[kind],
                }
            )
        for category, query, targets in case["questions"]:
            questions.append(
                {
                    "id": f"Q{len(questions) + 1:02}",
                    "topic": case["topic"],
                    "category": category,
                    "question": query,
                    "targets": [
                        {"document_id": ids[kind], "anchor": anchor} for kind, anchor in targets
                    ],
                }
            )
    return {"version": "rrf-v2-50", "documents": documents, "questions": questions}
