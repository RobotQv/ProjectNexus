    for did, project, filename, blocks in DOCUMENTS:
        documents.append(
            {
                "id": did,
                "project_id": project,
                "filename": filename,
                "blocks": [
                    {"id": did * 100 + n, "block_no": n, "heading": heading, "text": text}
                    for n, (heading, text) in enumerate(blocks)
                ],
            }
        )
    questions = []
    for n, (category, question, targets) in enumerate(QUESTIONS, 1):
        questions.append(
            {
                "question_id": f"B{n:02}",
                "batch": "B",
                "category": category,
                "project_id": 2 if n in (44, 49) else 1,
                "question": question,
                "relevant_anchors": [
                    {
                        "relevant_document_id": did,
                        "relevant_block_no": bno,
                        "relevant_anchor_text": anchor,
                    }
                    for did, bno, anchor in targets
                ],
                "distractor_note": "相同术语可能出现在历史决策、当前协议或另一项目；只依据本题作用域内的直接证据。",
                "no_answer_reason": "作用域内材料未提供问题要求的具体事实，不指定虚假正确锚点。"
                if not targets
                else None,
            }
        )
    return {"documents": documents, "questions": questions}
